"""Build the result tables from the saved suite runs (results/suite/) into results/summary/.

Every number comes from saved run files; nothing is typed in by hand. Detection scores are
micro-averaged over all 20 rounds of a run (summed counts), then mean +- std over seeds.
Accuracy and ASR are last-half means (rounds 11-20) per run, then mean +- std over seeds.
Shadow scores use each variant's tuned threshold from configs/tuned_thresholds.yaml.

Outputs: e1_distortion.csv, detection_vs_k.csv, e2_defences.csv, e3_label_skew.csv, e6_evasion.csv,
e5_scalability.csv (copied) and tables.md (all tables in Markdown).

Usage:  python experiments/summarize.py
"""

from __future__ import annotations

import csv
import json
import math
from collections import defaultdict
from pathlib import Path

import numpy as np
import yaml

from sybil_fl.metrics import detection_scores

REPO = Path(__file__).resolve().parents[1]
SUITE = REPO / "results" / "suite"
OUT = REPO / "results" / "summary"


def read_csv(path: Path) -> list[dict]:
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def write_csv(name: str, rows: list[dict]) -> None:
    if not rows:
        return
    with open(OUT / name, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def meta(run: Path) -> dict:
    return json.loads((run / "meta.json").read_text())


def ms(values: list[float]) -> tuple[float, float]:
    vals = [v for v in values if not math.isnan(v)]
    if not vals:
        return float("nan"), float("nan")
    return float(np.mean(vals)), float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0


def fmt(m: float, s: float, digits: int = 3) -> str:
    if math.isnan(m):
        return "n/a"
    return f"{m:.{digits}f} ± {s:.{digits}f}"


def shadow_scores(run: Path, method: str, k: int, tau: float) -> dict[str, float]:
    tot = {"tp": 0, "fp": 0, "fn": 0, "tn": 0}
    for r in read_csv(run / "shadow_detection.csv"):
        if r["method"] == method and int(r["k"]) == k and math.isclose(float(r["tau"]), tau):
            for c in tot:
                tot[c] += int(r[c])
    if sum(tot.values()) == 0:
        raise ValueError(f"no shadow rows for {method} k={k} tau={tau} in {run}")
    return detection_scores(**tot)


def md_table(title: str, rows: list[dict]) -> str:
    if not rows:
        return f"### {title}\n\n(no runs)\n"
    cols = list(rows[0])
    lines = [f"### {title}", "", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    tuned = yaml.safe_load((REPO / "configs" / "tuned_thresholds.yaml").read_text())
    variants = [("full", 0, tuned["full"])] + [
        ("projected", int(name.split("_k")[1]), tau) for name, tau in tuned.items() if name.startswith("projected_k")
    ]
    md = ["# Result tables (generated by experiments/summarize.py)\n",
          f"Tuned thresholds (seed 0): {tuned}\n"]

    # ---- E1: projection distortion of pairwise cosine, held-out attack + clean FedAvg runs
    e2 = SUITE / "e2"
    dist = defaultdict(lambda: defaultdict(list))
    for run in sorted(e2.glob("*_fedavg_s*")):
        for r in read_csv(run / "shadow_similarity.csv"):
            k = int(r["k"])
            for c in ("mean_abs_err", "p95_abs_err", "max_abs_err", "cos_sybil_sybil", "cos_honest_honest", "cos_sybil_honest"):
                dist[k][c].append(float(r[c]))
    e1 = []
    for k in sorted(dist):
        row = {"k": "full" if k == 0 else k}
        for c, vals in dist[k].items():
            m, s = ms(vals)
            row[c] = round(m, 4)
        e1.append(row)
    write_csv("e1_distortion.csv", e1)
    md.append(md_table("E1 — cosine distortion vs k (mean over rounds, seeds 1–3, clean + attack FedAvg runs)", e1))

    # ---- detection vs k (shadow on held-out undefended runs, tuned thresholds)
    dvk = []
    for method, k, tau in variants:
        f1, fpr_a, rec, fpr_c = [], [], [], []
        for s in (1, 2, 3):
            a = shadow_scores(e2 / f"attack_fedavg_s{s}", method, k, tau)
            c = shadow_scores(e2 / f"clean_fedavg_s{s}", method, k, tau)
            f1.append(a["f1"]); fpr_a.append(a["fpr"]); rec.append(a["recall"]); fpr_c.append(c["fpr"])
        dvk.append({"detector": "full" if method == "full" else f"projected k={k}", "tau": tau,
                    "F1 (attack)": fmt(*ms(f1)), "recall (attack)": fmt(*ms(rec)),
                    "FPR (attack)": fmt(*ms(fpr_a)), "FPR (clean)": fmt(*ms(fpr_c))})
    write_csv("detection_vs_k.csv", dvk)
    md.append(md_table("Detection vs k — shadow scoring on undefended FedAvg runs, held-out seeds 1–3", dvk))

    # ---- E2: defences
    e2rows = []
    for scen in ("clean", "attack"):
        for defence in ("fedavg", "median", "full", "projected"):
            runs = [e2 / f"{scen}_{defence}_s{s}" for s in (1, 2, 3)]
            sums = [meta(r)["summary"] for r in runs if (r / "meta.json").exists()]
            if not sums:
                continue
            row = {"scenario": scen, "defence": defence, "seeds": len(sums),
                   "acc (r11-20)": fmt(*ms([x["last_half_mean_test_acc"] for x in sums]), 4),
                   "ASR (r11-20)": fmt(*ms([x["last_half_mean_asr"] for x in sums]), 4)}
            if defence in ("full", "projected"):
                row["F1"] = fmt(*ms([x["detection_scores"]["f1"] for x in sums]))
                row["FPR"] = fmt(*ms([x["detection_scores"]["fpr"] for x in sums]))
                row["skipped rounds"] = sum(x["skipped_rounds"] for x in sums)
                row["detector ms/round"] = fmt(*ms([1e3 * (x["mean_seconds"]["t_matrix"] + x["mean_seconds"]["t_detect_projection"]
                                                          + x["mean_seconds"]["t_detect_similarity"] + x["mean_seconds"]["t_detect_clustering"])
                                                    for x in sums]), 1)
            else:
                row.update({"F1": "—", "FPR": "—", "skipped rounds": "—", "detector ms/round": "—"})
            e2rows.append(row)
    write_csv("e2_defences.csv", e2rows)
    md.append(md_table("E2 — defences, held-out seeds 1–3 (8 pool Sybils join 20 honest clients; 7 → 1)", e2rows))

    # ---- E3: label skew
    e3rows = []
    for alpha, runs_for in ((0.1, lambda sc, s: SUITE / "e3" / f"{sc}_alpha0.1_s{s}"),
                            (0.5, lambda sc, s: e2 / f"{sc}_fedavg_s{s}"),
                            (5.0, lambda sc, s: SUITE / "e3" / f"{sc}_alpha5.0_s{s}")):
        for method, k, tau in [v for v in variants if v[0] == "full" or v[1] == 64]:
            fpr_c, fpr_a, f1 = [], [], []
            for s in (1, 2):
                if not (runs_for("clean", s) / "shadow_detection.csv").exists():
                    continue
                c = shadow_scores(runs_for("clean", s), method, k, tau)
                a = shadow_scores(runs_for("attack", s), method, k, tau)
                fpr_c.append(c["fpr"]); fpr_a.append(a["fpr"]); f1.append(a["f1"])
            e3rows.append({"alpha": alpha, "detector": "full" if method == "full" else f"projected k={k}", "tau": tau,
                           "FPR (clean)": fmt(*ms(fpr_c)), "FPR (attack)": fmt(*ms(fpr_a)), "F1 (attack)": fmt(*ms(f1))})
    write_csv("e3_label_skew.csv", e3rows)
    md.append(md_table("E3 — false positives vs label skew (Dirichlet alpha), seeds 1–2, shadow scoring", e3rows))

    # ---- E6: evasion
    e6rows = []
    e6 = SUITE / "e6"
    modes = ("known_projection", "guessed_projection", "gaussian")
    budgets = sorted({float(p.name.split("_eps")[1].split("_s")[0]) for p in e6.glob("*_eps*_s*")}) if e6.exists() else []
    for mode in modes:
        for eps in [0.0] + budgets:
            runs = ([e2 / f"attack_projected_s{s}" for s in (1, 2)] if eps == 0.0
                    else [e6 / f"{mode}_eps{eps}_s{s}" for s in (1, 2)])
            runs = [r for r in runs if (r / "meta.json").exists() and "summary" in meta(r)]
            if not runs:
                continue
            sums = [meta(r)["summary"] for r in runs]
            full_rec = []
            if eps > 0:
                full_rec = [shadow_scores(r, "full", 0, tuned["full"])["recall"] for r in runs]
            e6rows.append({
                "attacker": mode, "budget": eps, "seeds": len(runs),
                "projected recall": fmt(*ms([x["detection_scores"]["recall"] for x in sums])),
                "projected FPR": fmt(*ms([x["detection_scores"]["fpr"] for x in sums])),
                "full-dim recall (shadow)": fmt(*ms(full_rec)) if full_rec else "see E2",
                "ASR (r11-20)": fmt(*ms([x["last_half_mean_asr"] for x in sums]), 4),
                "acc (r11-20)": fmt(*ms([x["last_half_mean_test_acc"] for x in sums]), 4),
            })
    write_csv("e6_evasion.csv", e6rows)
    md.append(md_table("E6 — evasion vs the projected defence (k = 64), seeds 1–2", e6rows))

    # ---- E5: copy
    e5 = SUITE / "e5" / "scalability.csv"
    if e5.exists():
        rows = read_csv(e5)
        write_csv("e5_scalability.csv", rows)  # rewritten (not copied) so the committed file has LF endings
        md.append(md_table("E5 — synthetic runtime (median of 5, seconds)", [
            {"grid": r["grid"], "n": r["n"], "d": r["d"], "k": r["k"],
             "full sim": f"{float(r['full_similarity']):.4f}", "SHAKE gen": f"{float(r['gen_shake256']):.4f}",
             "PCG64 gen": f"{float(r['gen_pcg64']):.4f}", "project": f"{float(r['project']):.4f}",
             "proj sim": f"{float(r['projected_sim']):.5f}", "proj total": f"{float(r['projected_total_shake256']):.4f}",
             "stored full MB": f"{int(r['stored_full_bytes'])/1e6:.2f}", "stored proj MB": f"{int(r['stored_projected_bytes'])/1e6:.4f}"}
            for r in rows]))

    (OUT / "tables.md").write_text("\n".join(md), encoding="utf-8", newline="\n")
    print(f"wrote {len(list(OUT.glob('*.csv')))} CSV tables and {OUT / 'tables.md'}")  # console may not be UTF-8


if __name__ == "__main__":
    main()
